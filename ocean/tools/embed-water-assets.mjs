#!/usr/bin/env node
// Turn the original PNG water-detail assets into a small ES module.
//
// The demos can run as normal modules, but tools/bundle-three.mjs also emits a
// completely self-contained HTML file. Keeping the source PNGs and generating
// this module gives both paths the same bytes without a runtime URL fetch.
//
//   node tools/embed-water-assets.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const ASSETS = join( ROOT, 'src', 'assets' );
const OUT = join( ROOT, 'src', 'generated-water-assets.js' );

const encode = async ( name ) => (

	( await readFile( join( ASSETS, name ) ) ).toString( 'base64' )

);

const foam = await encode( 'foam-lace.png' );
const wakeFoam = await encode( 'wake-foam-pack.png' );
const splash = await encode( 'splash-atlas.png' );

const source = `// Generated by tools/embed-water-assets.mjs. Do not edit by hand.
// Original, project-owned source PNGs live in src/assets/.

export const FOAM_LACE_PNG_BASE64 = '${ foam }';
export const WAKE_FOAM_PACK_PNG_BASE64 = '${ wakeFoam }';
export const SPLASH_ATLAS_PNG_BASE64 = '${ splash }';
`;

await writeFile( OUT, source );
console.log( `embedded water assets -> ${ OUT }` );
