#!/usr/bin/env node
// Measure every one-shot — the shared library's and the episode's voice
// clips both — and write company/library/audio-timing.js.
//
//   node tools/measure-audio.mjs
//
// Two numbers per clip, and the piece needs both:
//
//   onset  seconds of near-silence before the sound actually starts. A cue
//          fires on a beat, but the sound arrives `onset` later, so a slap
//          with 90ms of encoder padding lands 90ms after the wing connects.
//          Playback seeks past it.
//   loud   RMS of the hottest 300ms window — how loud the clip actually is to
//          a listener, which peak does not tell you. Dialogue is levelled
//          against this so a whispered line is not lost under the rain.
//
// Music beds are skipped — they are long, and they already measure within a
// third of each other. Ambience loops are measured: the fountain came back 19x
// quieter than the rain, which is not a mix decision anyone made.

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, join, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BEDS = /^mus-/;

async function loadPlaywright() {
  for (const c of ['playwright', '/opt/node22/lib/node_modules/playwright/index.mjs',
    '/usr/lib/node_modules/playwright/index.mjs', process.env.PLAYWRIGHT_PATH].filter(Boolean)) {
    try { return await import(c); } catch { /* next */ }
  }
  throw new Error('playwright not found');
}

// The clips live in two places now: the library any episode shares, and the
// voice track of this one. Levelling has to see them all — dialogue is what
// everything else is levelled against.
const DIRS = ['company/library/audio', 'episodes/e01-corazon/voice'];
const clips = [];
for (const dir of DIRS) {
  for (const f of (await readdir(join(ROOT, dir))).filter((f) => f.endsWith('.mp3'))) {
    clips.push({ id: f.slice(0, -4), url: `/${dir}/${f}` });
  }
}
clips.sort((a, b) => a.id.localeCompare(b.id));
const oneShots = clips.filter((c) => !BEDS.test(c.id));

const server = createServer(async (req, res) => {
  try {
    const p = join(ROOT, decodeURIComponent(req.url.split('?')[0]));
    if (!p.startsWith(ROOT)) { res.writeHead(403).end(); return; }
    res.writeHead(200, { 'content-type': extname(p) === '.mp3' ? 'audio/mpeg' : 'text/html' });
    res.end(await readFile(p));
  } catch { res.writeHead(404).end(); }
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));

const { chromium } = await loadPlaywright();
const browser = await chromium.launch({ args: ['--disable-dev-shm-usage', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
await page.goto(`http://127.0.0.1:${server.address().port}/tools/voices.html`, { waitUntil: 'load' });
const rows = await page.evaluate(([clips]) => window.__measure(clips, 30), [oneShots]);
await browser.close();
server.close();

rows.sort((a, b) => a.id.localeCompare(b.id));
await writeFile(join(ROOT, 'company/library/audio-timing.js'), `// GENERATED by tools/measure-audio.mjs — do not edit.
//
// onset  leading near-silence, skipped at playback so the attack lands on the
//        cue rather than a tenth of a second after it
// dur    length of the sounding part
// peak   loudest single sample
// loud   RMS of the hottest 300ms window — the number to level against

export const CLIP = {
${rows.map((r) => `  ${JSON.stringify(r.id)}: { onset: ${r.lead.toFixed(3)}, dur: ${r.dur.toFixed(2)}, peak: ${r.peak.toFixed(3)}, loud: ${r.loud.toFixed(4)} },`).join('\n')}
};
`);

console.log('clip                onset    dur    peak     loud');
for (const r of rows.sort((a, b) => b.lead - a.lead)) {
  const flag = r.lead > 0.06 ? '  <-- late attack' : '';
  console.log(`${r.id.padEnd(18)} ${r.lead.toFixed(3)}  ${r.dur.toFixed(2)}  ${r.peak.toFixed(3)}  ${r.loud.toFixed(4)}${flag}`);
}
